def update_triples_with_kinship(csv_path: str, kinships: list, output_path: str):
    """更新三元组文件，添加亲属关系"""
    
    # 读取原有三元组
    triples = []
    with open(csv_path, 'r', encoding='utf-8-sig') as f:
        reader = csv.DictReader(f)
        for row in reader:
            triples.append(row)
    
    # 添加亲属关系三元组
    for subject, obj, kinship_type in kinships:
        triples.append({
            '主体': subject,
            '关系': '亲属',
            '客体': obj
        })
    
    # 保存更新后的三元组
    with open(output_path, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.DictWriter(f, fieldnames=['主体', '关系', '客体'])
        writer.writeheader()
        for triple in triples:
            writer.writerow({
                '主体': triple['主体'],
                '关系': triple['关系'],
                '客体': triple['客体']
            })
    
    return len(triples)


